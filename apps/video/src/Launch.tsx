import { AbsoluteFill, Audio, Sequence, staticFile } from "remotion"
import { SceneFade } from "./kit"
import { Board, Cost, End, Faders, Flat, Guarded, Install, Lamps, LightsUp, Wall } from "./scenes"
import "./style.css"

/** Scenes in order, with their lengths in frames (30 fps). */
const timeline = [
  { Scene: Flat, length: 78 },
  { Scene: LightsUp, length: 96 },
  { Scene: Guarded, length: 150 },
  { Scene: Lamps, length: 135 },
  { Scene: Faders, length: 150 },
  { Scene: Cost, length: 120 },
  { Scene: Board, length: 135 },
  { Scene: Wall, length: 180 },
  { Scene: Install, length: 126 },
  { Scene: End, length: 108 },
]

const overlap = 8
export const launchLength = timeline.reduce((sum, s) => sum + s.length - overlap, overlap)

export function Launch() {
  let start = 0
  return (
    <AbsoluteFill style={{ background: "var(--night)" }}>
      {/* An original score timed to these scenes: generated by score/score.py. */}
      <Audio src={staticFile("score.mp3")} />
      {timeline.map(({ Scene, length }, i) => {
        const from = start
        start += length - overlap
        return (
          <Sequence key={i} from={from} durationInFrames={length}>
            <SceneFade length={length} fade={i === 0 ? 1 : overlap}>
              <Scene />
            </SceneFade>
          </Sequence>
        )
      })}
    </AbsoluteFill>
  )
}
