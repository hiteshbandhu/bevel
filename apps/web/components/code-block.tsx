import { cn } from "@workspace/ui/lib/utils"
import { highlight } from "@/lib/source"
import { CopyButton } from "@/components/copy-button"

export async function CodeBlock({
  code,
  lang = "tsx",
  title,
  className,
}: {
  code: string
  lang?: "tsx" | "css" | "bash" | "json"
  title?: string
  className?: string
}) {
  const html = await highlight(code, lang)
  return (
    <figure className={cn("overflow-hidden rounded-xl border bg-card", className)}>
      <div className="flex h-10 items-center justify-between border-b pr-1.5 pl-4">
        <figcaption className="font-mono text-xs text-muted-foreground">{title ?? lang}</figcaption>
        <CopyButton value={code} />
      </div>
      <div
        className="max-h-[32rem] overflow-auto p-4 [&_pre]:outline-none"
        // Generated by Shiki from our own source files.
        dangerouslySetInnerHTML={{ __html: html }}
      />
    </figure>
  )
}
